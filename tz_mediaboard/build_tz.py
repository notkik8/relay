def run(t, b=False, sz=None, caps=False):
    pr = FONT + ('<w:b/>' if b else '') + ('<w:caps/>' if caps else '')
    if sz:
        pr += f'<w:sz w:val="{sz}"/><w:szCs w:val="{sz}"/>'
    return f'<w:r><w:rPr>{pr}</w:rPr><w:t xml:space="preserve">{escape(t)}</w:t></w:r>'


def para(t="", style=None, jc=None, b=False, sz=None, ind=None, spacing=None, keep=False, pagebreak=False, num=False, raw_runs=None):
    pp = ''
    if style: pp += f'<w:pStyle w:val="{style}"/>'
    if keep: pp += '<w:keepNext/>'
    if pagebreak: pp += '<w:pageBreakBefore/>'
    if num: pp += '<w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/></w:numPr>'
    if spacing: pp += spacing
    if ind: pp += ind
    if jc: pp += f'<w:jc w:val="{jc}"/>'
    body = raw_runs if raw_runs is not None else (run(t, b, sz) if t else '')
    return f'<w:p><w:pPr>{pp}</w:pPr>{body}</w:p>'


