def cell(w, content, borders=False, vm=None, span=None, shade=False):
    pr = f'<w:tcW w:w="{w}" w:type="dxa"/>'
    if span: pr += f'<w:gridSpan w:val="{span}"/>'
    if vm == "restart": pr += '<w:vMerge w:val="restart"/>'
    elif vm == "cont": pr += '<w:vMerge/>'
    pr += '<w:vAlign w:val="center"/>' if borders else ''
    return f'<w:tc><w:tcPr>{pr}</w:tcPr>{content}</w:tc>'


def sigtable(rows, widths):
    """Подписные блоки титульного листа: таблица без границ."""
    x = ('<w:tbl><w:tblPr><w:tblW w:w="9355" w:type="dxa"/><w:tblLayout w:type="fixed"/>'
         '<w:tblCellMar><w:left w:w="40" w:type="dxa"/><w:right w:w="40" w:type="dxa"/></w:tblCellMar></w:tblPr><w:tblGrid>'
         + ''.join(f'<w:gridCol w:w="{w}"/>' for w in widths) + '</w:tblGrid>')
    for r in rows:
        x += '<w:tr><w:trPr><w:cantSplit/></w:trPr>'
        for w, (txt, sz, jc) in zip(widths, r):
            x += cell(w, tp(txt, sz=sz, jc=jc))
        x += '</w:tr>'
    return x + '</w:tbl>'


