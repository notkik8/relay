import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.RELAY_PLAYWRIGHT_DIR ?? 'playwright')
const [base = 'http://127.0.0.1:8180', screenshots = '/tmp/relay-discovery-smoke'] = process.argv.slice(2)
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1060 }, reducedMotion: 'reduce' })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const cards = page.locator('.relay-masonry [data-material]')
const related = page.getByRole('region', { name: 'Похожие находки' })
const panel = page.getByRole('dialog')
const cfg = () => page.evaluate(() => JSON.parse(localStorage.getItem('relay.discovery.v1') || '{}'))
const ids = (locator = cards) => locator.evaluateAll((items) => items.map((item) => item.dataset.material))
const home = async () => {
  await page.getByRole('link', { name: 'Relay — лента' }).click()
  await page.waitForURL((url) => url.pathname === '/' && !url.search)
}
const back = () => page.getByRole('button', { name: 'Назад', exact: true }).click()
const search = page.getByRole('searchbox')
const openPin = (card) => card.getByRole('link', { name: /^Открыть / }).click()

try {
  await mkdir(screenshots, { recursive: true })
  const response = await context.request.get(base + '/discovery/catalog.json')
  assert.ok(response.ok())
  const data = await response.json()
  assert.equal(new Set(data.map((item) => item.kind)).size, 3)
  assert.ok(data.length >= 1_000)
  assert.equal(new Set(data.map((item) => item.id)).size, data.length)

  await page.goto(base, { waitUntil: 'domcontentloaded' })
  await cards.first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'Обновить ленту' }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Кино', exact: true }).count(), 0)
  assert.ok(await page.locator('.relay-card-kind-track').count() > 0)
  assert.ok(await page.locator('.relay-card-kind-film').count() > 0)
  const homeLink = page.getByRole('link', { name: 'Relay — лента' })
  assert.equal(await homeLink.innerText(), 'Relay')
  assert.equal(await homeLink.locator('img, svg').count(), 0)
  assert.equal(await page.locator('head link[rel~="icon"], head link[rel^="apple-touch-icon"]').count(), 0)
  await page.waitForFunction(() => [...document.querySelectorAll('.relay-masonry img')].slice(0, 9)
    .filter((img) => img.naturalWidth > 0).length >= 4)
  await page.screenshot({ path: resolve(screenshots, 'desktop.png') })

  const firstIds = await ids()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await cards.first().waitFor()
  const reloadedIds = await ids()
  assert.notDeepEqual(reloadedIds.slice(0, 20), firstIds.slice(0, 20), 'A page reload rebuilds the ranking')

  const pinId = 'wm-100018646'
  const photo = page.locator(`[data-material="${pinId}"]`)
  await search.fill('горы над облаками')
  await photo.waitFor()
  await openPin(photo)
  await page.waitForURL(`**/pin/${pinId}`)
  await page.getByRole('heading', { name: 'Горы над облаками', exact: true }).waitFor()
  assert.equal(await panel.count(), 0)
  assert.ok(await page.getByRole('link', { name: 'Источник' }).getAttribute('href'))
  const relatedCards = related.locator('[data-material]')
  await relatedCards.first().waitFor()
  assert.ok(!(await ids(relatedCards)).includes(pinId))
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранено', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Копировать ссылку' }).click()
  await page.getByText('Скопировано', { exact: true }).or(page.getByRole('textbox', { name: 'Ссылка на материал' })).waitFor()
  await page.locator('.relay-detail-art img').evaluate((img) => img.decode())
  await page.screenshot({ path: resolve(screenshots, 'detail.png') })

  const markerCount = await relatedCards.count()
  await related.getByRole('button', { name: 'Ещё материалы' }).scrollIntoViewIfNeeded()
  await page.waitForFunction((count) => document.querySelectorAll('.relay-related [data-material]').length > count, markerCount)
  const loaded = await ids(relatedCards)
  assert.equal(loaded.length, new Set(loaded).size)
  const nextPin = relatedCards.nth(markerCount - 1)
  const nextId = await nextPin.getAttribute('data-material')
  await nextPin.scrollIntoViewIfNeeded()
  const scroll = await page.evaluate(() => window.scrollY)
  await openPin(nextPin)
  await page.waitForURL(`**/pin/${nextId}`)
  await back()
  await page.waitForURL(`**/pin/${pinId}`)
  await page.waitForFunction(({ scroll, nextId }) =>
    Math.abs(window.scrollY - scroll) < 100 && document.activeElement?.id === `pin-link-${nextId}`, { scroll, nextId })
  assert.ok(await relatedCards.count() >= loaded.length)

  await back()
  await page.waitForURL((url) => url.searchParams.get('q') === 'горы над облаками')
  await page.getByRole('link', { name: 'Сохранённое', exact: true }).click()
  await photo.waitFor()
  await photo.getByRole('button', { name: /^Убрать из сохранённого/ }).click()
  await page.getByRole('heading', { name: 'Здесь пока пусто' }).waitFor()
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await photo.waitFor()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await photo.waitFor()
  assert.deepEqual((await cfg()).saved, [pinId])

  await home()
  await search.fill('этого материала точно нет 99999')
  await page.getByRole('heading', { name: /ничего не нашлось/ }).waitFor()
  assert.equal(await search.inputValue(), 'этого материала точно нет 99999')
  await page.getByRole('button', { name: 'Очистить запрос' }).click()
  await cards.first().waitFor()
  await search.fill('горы над облаками')
  await openPin(photo)
  await page.getByRole('button', { name: 'Меньше такого' }).click()
  await page.getByRole('button', { name: 'Отменить', exact: true }).waitFor()
  assert.ok((await cfg()).hidden.includes(pinId))
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  assert.ok(!(await cfg()).hidden.includes(pinId))
  await photo.waitFor()
  await openPin(photo)
  await page.getByRole('button', { name: 'Меньше такого' }).click()
  await page.waitForURL((url) => url.pathname === '/' && url.searchParams.get('q') === 'горы над облаками')
  const updates = (await cfg()).model.updates
  await page.getByRole('button', { name: 'Закрыть уведомление' }).click()
  assert.ok((await cfg()).model.updates > updates, 'Confirmed hiding trains the model')

  await search.fill('гимнопедия')
  await page.waitForURL((url) => url.pathname === '/' && url.searchParams.get('q') === 'гимнопедия')
  const track = page.locator('[data-material="im-gymnopedie"]')
  await track.getByRole('button', { name: /^Послушать/ }).click()
  await track.getByRole('button', { name: /^Остановить/ }).waitFor()
  assert.equal(new URL(page.url()).pathname, '/')
  await track.getByRole('button', { name: /^Остановить/ }).click()
  await track.getByRole('button', { name: /^Послушать/ }).waitFor()
  await page.goto(base + '/?m=im-gymnopedie', { waitUntil: 'domcontentloaded' })
  await page.waitForURL('**/pin/im-gymnopedie')
  await page.locator('audio').waitFor()
  const player = await page.locator('audio').boundingBox()
  assert.ok(player)
  await page.mouse.click(player.x + 18, player.y + player.height / 2)
  await page.waitForFunction(() => document.querySelector('audio')?.currentTime > .2)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.locator('audio').waitFor()
  await back()

  await page.getByRole('button', { name: 'Настройки ленты' }).click()
  await panel.getByRole('checkbox').uncheck()
  assert.equal((await cfg()).personalize, false)
  const before = (await cfg()).model.updates
  await panel.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await openPin(cards.first())
  assert.equal((await cfg()).model.updates, before)
  await page.getByRole('button', { name: 'Настройки ленты' }).click()
  await panel.getByRole('button', { name: 'Сбросить предпочтения' }).click()
  assert.equal((await cfg()).model.updates, 0)
  assert.deepEqual((await cfg()).saved, [pinId])

  const mobile = await browser.newPage({ viewport: { width: 360, height: 850 }, isMobile: true, hasTouch: true })
  await mobile.goto(base, { waitUntil: 'domcontentloaded' })
  await mobile.locator('.relay-masonry .relay-card').first().waitFor()
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth === innerWidth))
  const bookmark = await mobile.getByRole('button', { name: /^Сохранить —/ }).first().boundingBox()
  assert.ok(bookmark && bookmark.width >= 44 && bookmark.height >= 44)
  await mobile.waitForFunction(() => [...document.querySelectorAll('.relay-masonry img')].slice(0, 6)
    .filter((img) => img.naturalWidth > 0).length >= 3)
  await mobile.screenshot({ path: resolve(screenshots, 'mobile.png') })
  await mobile.goto(`${base}/pin/${pinId}`, { waitUntil: 'domcontentloaded' })
  await mobile.locator('.relay-detail-art img').evaluate((img) => img.decode())
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth === innerWidth))
  await mobile.screenshot({ path: resolve(screenshots, 'mobile-detail.png') })
  assert.deepEqual(errors, [])
  console.log('OK: reload, pin history and scroll, related pagination, search, undo, audio, preferences, text home link and 360px')
} catch (error) {
  console.error('Failed at', page.url(), 'with', await cards.count(), 'cards')
  throw error
} finally {
  await browser.close()
}
